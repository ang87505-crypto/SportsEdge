/** Builds the reviewable, additive owner SQL bundle from versioned schema sources. No network or database calls. */
import {readFileSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
const root=new URL('../',import.meta.url);
const body=(name:string)=>{
 const s=readFileSync(new URL('database/props/'+name,root),'utf8');
 if(!s.includes('\nBEGIN;')||!s.trimEnd().endsWith('COMMIT;'))throw Error('SETUP_TRANSACTION_CONTRACT');
 return s.replace(/\nBEGIN;/,'\n').replace(/COMMIT;\s*$/,'');
};
export function forwardSetupSql(){
 const parts=[{group:'lab',names:['props_lab_experiments','props_lab_events','props_lab_predictions','props_lab_flags','props_lab_reports','props_lab_stakes','props_lab_prediction_tampering'],file:'props_lab_v1.sql'},
  {group:'penny',names:['props_penny_cohorts','props_penny_entries','props_penny_settlements','props_penny_tampering'],file:'props_penny_paper_v1.sql'}];
 return '-- Generated by scripts/build-forward-study-setup.ts. Additive, atomic and safe to re-run.\n'+
  '-- Apply to the ACTIVE PROPS database configured as SPORTSEDGE_PROPS_SUPABASE_URL.\n'+
  '-- Creates only missing, complete study schemas. Existing study rows and original paper accounts are preserved.\nBEGIN;\n'+
  'DO $forward_setup$ DECLARE present integer; BEGIN\n'+
  " IF to_regclass('public.props_observations') IS NULL OR to_regclass('public.props_entries') IS NULL THEN RAISE EXCEPTION 'WRONG_DATABASE: select the existing props ledger project'; END IF;\n"+
  parts.map(p=>" SELECT count(*) INTO present FROM unnest(ARRAY["+p.names.map(n=>"'public."+n+"'").join(',')+"]::text[]) n WHERE to_regclass(n) IS NOT NULL;\n"+
   ' IF present=0 THEN EXECUTE $'+p.group+'_ddl$\n'+body(p.file)+'\n$'+p.group+'_ddl$;\n'+
   ' ELSIF present<>'+p.names.length+" THEN RAISE EXCEPTION 'PARTIAL_"+p.group.toUpperCase()+"_SCHEMA: inspect before proceeding'; END IF;\n").join('')+
  'END $forward_setup$;\n'+
  'DO $study_grants$ DECLARE t text; BEGIN\n'+
  " FOREACH t IN ARRAY ARRAY['props_lab_experiments','props_lab_events','props_lab_predictions','props_lab_flags','props_lab_reports','props_lab_stakes','props_penny_cohorts','props_penny_entries','props_penny_settlements'] LOOP\n"+
  " EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);\n"+
  " EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC,anon,authenticated,service_role',t);\n"+
  " EXECUTE format('GRANT SELECT,INSERT ON public.%I TO service_role',t); END LOOP;\n"+
  'END $study_grants$;\nNOTIFY pgrst, \'reload schema\';\nCOMMIT;\n';
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const i=process.argv.indexOf('--out');if(i<0||!process.argv[i+1])throw Error('SETUP_MISSING_OUT');
 writeFileSync(process.argv[i+1],forwardSetupSql());
}
